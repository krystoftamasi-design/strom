import assert from 'node:assert/strict';
import { TreeEcology } from '../ekologie/tree_ecology.js';
import { konstanty } from '../ekologie/tree_ecology_vzorce.js';

const tree = new TreeEcology();
tree.configure({ height: 26, woodVolume: 4, crownArea: 100 });
tree.setWindowValue('photosynthesis', 0.4);
assert.ok(Math.abs(tree.activity - 0.4) < 1e-10);
assert.ok(Math.abs(tree.oxygenGramsPerMinute - tree.glucoseGramsPerMinute * konstanty.oxygenPerGlucose) < 1e-10);
assert.ok(Math.abs(tree.co2GramsPerMinute - tree.leafArea * 0.4 * konstanty.co2Conversion) < 1e-10);
const override = tree.manualPhotosynthesis.weight;
tree.step(60);
assert.ok(tree.manualPhotosynthesis.weight < override, 'Automatic conditions regain influence with model time');
tree.setWindowValue('water', 0);
assert.equal(tree.consumption, 0);
const before = tree.reserve;
tree.step(1);
assert.ok(Number.isFinite(tree.reserve) && tree.reserve >= 0 && tree.reserve <= tree.capacity);
assert.ok(Number.isFinite(tree.consumption) && tree.manualConsumption.weight < 1);
assert.notEqual(tree.reserve, before, 'The water intervention participates in the water balance');
console.log('PASS: linked photosynthesis values, water balance and automatic recovery.');
