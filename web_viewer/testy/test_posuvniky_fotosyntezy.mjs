import assert from 'node:assert/strict';
import { TreeEcology } from '../ekologie/tree_ecology.js';
import { konstanty } from '../ekologie/tree_ecology_vzorce.js';

const tree = new TreeEcology();
tree.configure({ height: 26, woodVolume: 4, crownArea: 100 });
assert.ok(Math.abs(tree.waterInput - tree.seasonalWaterLimit * 0.9) < 1e-10, 'Automatic supply leaves room below the root limit');
tree.setSeason('spring');
assert.ok(Math.abs(tree.waterInput - tree.seasonalWaterLimit * 0.9) < 1e-10, 'A season change restores the reduced automatic supply');
assert.ok(Math.abs(tree.oxygenGramsPerMinute - tree.glucoseGramsPerMinute * konstanty.oxygenPerGlucose) < 1e-10);
assert.ok(Math.abs(tree.co2GramsPerMinute - tree.activeLeafArea * tree.photosynthesisEfficiency * konstanty.co2Conversion) < 1e-10);
const supplied = tree.baseTranspiration * 2;
tree.setWaterInput(supplied);
assert.equal(tree.waterInput, supplied, 'The control changes water availability');
assert.ok(tree.inflow <= tree.seasonalWaterLimit, 'Root uptake remains capped');
assert.ok(tree.inflow < tree.waterInput, 'Extra availability does not force extra uptake');
tree.step(5);
assert.equal(tree.waterInput, supplied, 'The chosen availability remains set while the simulation runs');
assert.ok(tree.reserve >= 0 && tree.reserve <= tree.capacity, 'Water reserve remains within bounds');
tree.sunElevation = -20;
tree.evaluate(0);
assert.equal(tree.glucoseGramsPerMinute, 0, 'Photosynthesis stops in the dark');
assert.ok(tree.respirationSugar > 0 && tree.respirationOxygen > 0 && tree.respirationCO2 > 0, 'Respiration continues in the dark');
assert.ok(Math.abs(tree.respirationOxygen - tree.respirationSugar * konstanty.oxygenPerGlucose) < 1e-10);
assert.ok(Math.abs(tree.respirationCO2 - tree.respirationSugar * konstanty.co2Conversion / konstanty.glucoseConversion) < 1e-10);
const firstTemperature = tree.ambientTemperature;
const firstRespiration = tree.respirationSugar;
tree.hourOfDay = 15;
tree.evaluate(0);
const limited = t => Math.max(-10, Math.min(40, t));
assert.ok(Math.abs(tree.respirationSugar / firstRespiration - 2 ** ((limited(tree.ambientTemperature) - limited(firstTemperature)) / 10)) < 1e-10, 'Respiration follows its temperature response');
console.log('PASS: photosynthesis relationships and bounded water availability.');
